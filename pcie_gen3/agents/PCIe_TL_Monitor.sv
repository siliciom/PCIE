    r_x.fmt    = dw[31:29];
    r_x.r_type = dw[28:24];
    r_x.length = dw[9:0];
    r_x.td     = dw[15];
    r_x.at     = dw[11:10];

    // header DW count
    case(r_x.fmt)
      3'b000, 3'b010 : header_dw = 3;
      3'b001, 3'b011 : header_dw = 4;
      default        : header_dw = 3;
    endcase

    ////////////////////////////// REMAINING HEADER //////////////////////////////
