          r_x.e_type = CFG_RD0;
        else
          r_x.e_type = CFG_WR0;

      5'b00101 :
        if(r_x.fmt == 3'b000)
          r_x.e_type = CFG_RD1;
        else
          r_x.e_type = CFG_WR1;

      5'b01010 :
        if(r_x.fmt inside {3'b000, 3'b010})
          r_x.e_type = CPL;
        else
          r_x.e_type = CPL_DATA;

    endcase


    // header DW count
    case(r_x.fmt)
      3'b000, 3'b010 : header_dw = 3;
      3'b001, 3'b011 : header_dw = 4;
      default         : header_dw = 3;
    endcase

    ////////////////////////////// REMAINING HEADER //////////////////////////////
    for(int i = 1; i < header_dw; i++) begin
      do begin
        @(posedge TX_TL_DL.CLK);
      end while(!(TX_TL_DL.tl_rx_valid && TX_TL_DL.tl_rx_ready));
      dw = TX_TL_DL.tl_rx_data;
      r_x.tlp_q.push_back(dw);
    end

    r_x.req_id = r_x.tlp_q[1][31:16];
    r_x.tag    = r_x.tlp_q[1][15:8];

    `uvm_info("TX_TL_MONITOR", $sformatf("[%s] REQ_ID = %0d TAG = %0d", tag, r_x.req_id, r_x.tag), UVM_LOW)

    if(header_dw >= 3) begin
      r_x.addr = r_x.tlp_q[2];
    end

    ////////////////////////////// PAYLOAD //////////////////////////////
    payload_dw = r_x.length;

    if(r_x.fmt inside {3'b010, 3'b011}) begin
      r_x.payload = new[payload_dw];
      for(int i = 0; i < payload_dw; i++) begin
        do begin
          @(posedge TX_TL_DL.CLK);
        end while(!(TX_TL_DL.tl_rx_valid && TX_TL_DL.tl_rx_ready));
        dw = TX_TL_DL.tl_rx_data;
        r_x.payload[i] = dw;
        r_x.tlp_q.push_back(dw);
      end
    end

    ////////////////////////////// ECRC CHECK //////////////////////////////
    if(r_x.td) begin
      do begin
        @(posedge TX_TL_DL.CLK);
      end while(!(TX_TL_DL.tl_rx_valid && TX_TL_DL.tl_rx_ready));
      dw = TX_TL_DL.tl_rx_data;
      r_x.ECRC = dw;

      calculated_ecrc = r_x.calculate_ecrc();

      `uvm_info("TX_TL_MONITOR", $sformatf("[%s] RX ECRC CHECK: RECEIVED=%08h CALCULATED=%08h", tag, r_x.ECRC, calculated_ecrc), UVM_LOW)

      if(calculated_ecrc == r_x.ECRC) begin
        r_x.ecrc_error   = 1'b0;
        r_x.compl_status = 3'b000;
        r_x.tlp_q.push_back(r_x.ECRC);

        foreach(r_x.tlp_q[i])
          `uvm_info("TX_TL_MONITOR", $sformatf("[%s] TX_TLP[%0d] = %08h @ %0t", tag, i, r_x.tlp_q[i], $time), UVM_LOW)

        TX_TL_Send.write(r_x);

      end else begin
        r_x.ecrc_error = 1'b1;
        `uvm_error("TX_TL_MONITOR", $sformatf("[%s] ECRC MISMATCH - PACKET DROPPED", tag))
      end

    end else begin
      r_x.ecrc_error   = 1'b0;
      r_x.compl_status = 3'b000;

      foreach(r_x.tlp_q[i])
        `uvm_info("TX_TL_MONITOR", $sformatf("[%s] TX_TLP[%0d] = %08h @ %0t", tag, i, r_x.tlp_q[i], $time), UVM_LOW)

      TX_TL_Send.write(r_x);
    end

    wait(TX_TL_DL.tl_rx_valid == 0);

  endtask : rc_collecting_rx_completion



