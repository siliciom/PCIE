    int header_dw;
    int payload_dw;
    bit [31:0] calculated_ecrc;

    ////////////////////////////// HEADER DW0 //////////////////////////////
    do begin
      @(posedge TX_TL_DL.CLK);
    end while(!(TX_TL_DL.tl_rx_valid && TX_TL_DL.tl_rx_ready));

    dw = TX_TL_DL.tl_rx_data;

    r_x.tlp_q.delete();
    r_x.tlp_q.push_back(dw);

    r_x.fmt    = dw[31:29];
    r_x.r_type = dw[28:24];
    r_x.length = dw[9:0];
    r_x.td     = dw[15];
 case(r_x.r_type)
      5'b00000 :
        if(r_x.fmt inside {3'b000, 3'b001})
          r_x.e_type = MEM_RD;
