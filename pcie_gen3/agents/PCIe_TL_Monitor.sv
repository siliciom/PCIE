  // EP_MODE tasks - preserved exactly as RX_TL_Monitor.sv
  //=============================================================

  task ep_collecting_tx_request(Sequence_item r_x);

    bit [31:0] dw;
    int header_dw;
    int payload_dw;
    bit [31:0] calculated_ecrc;

    ////////////////////////////// HEADER DW0 //////////////////////////////
